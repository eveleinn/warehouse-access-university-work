INSERT INTO [Количество материала на складе в наличии] ( Материал, Склад, [Количество в наличии] )
SELECT P.[Материал], P.[Склад],
       Nz(Sum(P.Количество),0) - Nz(Sum(V.Количество),0) AS [Количество в наличии]
FROM [Количество поставленного материала] AS P
LEFT JOIN [Количество выданного материала] AS V
ON (P.Материал = V.Материал) AND (P.Склад = V.Склад)
GROUP BY P.[Материал], P.[Склад];